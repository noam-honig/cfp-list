export function regionsOf(location: string): RegionId[] {
  const text = (location || '').trim()
  const found = patterns.filter(([, re]) => re.test(text)).map(([id]) => id)
  return found.length ? found : ['other']
}

export const isInIsrael = (location: string) =>
  regionsOf(location).includes('israel')
